import tempfile
import unittest
from pathlib import Path

from sql_converter.engine import convert_file, convert_text, read_sql
from sql_converter.mappings import load_overrides, replace_type, save_overrides
from sql_converter.scanner import split_sql, split_top_level, convert_identifier_quotes


class SqlScannerTests(unittest.TestCase):
    def test_semicolon_inside_literals_and_comments(self):
        text = "INSERT INTO t VALUES('a;b'); -- x;y\nINSERT INTO t VALUES('c');"
        self.assertEqual(len(split_sql(text)), 2)

    def test_dollar_quoted_body_is_one_statement(self):
        text = "CREATE FUNCTION x() RETURNS void AS $$ BEGIN RAISE NOTICE 'a;b'; END $$ LANGUAGE plpgsql;"
        self.assertEqual(len(split_sql(text)), 1)

    def test_table_expression_comma(self):
        self.assertEqual(split_top_level("id NUMERIC(12,3), name VARCHAR(80), a DEFAULT 'x,y'"), [
            "id NUMERIC(12,3)", "name VARCHAR(80)", "a DEFAULT 'x,y'"])

    def test_quote_conversion_does_not_touch_string_literals(self):
        self.assertEqual(convert_identifier_quotes("SELECT `a`,'`x`'", 'mysql_to_opengauss'), 'SELECT "a",\'`x`\'')
        self.assertEqual(convert_identifier_quotes('SELECT "a"', 'opengauss_to_mysql'), 'SELECT `a`')


class SqlConverterTests(unittest.TestCase):
    def test_mysql_create_table_indexes_auto_increment(self):
        text = '''CREATE TABLE `rel` (
          `id` BIGINT NOT NULL AUTO_INCREMENT,
          `file_id` BIGINT UNSIGNED NOT NULL,
          `created` DATETIME(6),
          `active` TINYINT(1) DEFAULT 0,
          PRIMARY KEY (`id`),
          UNIQUE KEY `uk_pair` (`id`,`file_id`),
          KEY `idx_created` (`created`,`active`)
        ) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;'''
        sql, report = convert_text(text, 'mysql_to_opengauss')
        self.assertTrue(report.ready)
        self.assertIn('GENERATED BY DEFAULT AS IDENTITY', sql)
        self.assertIn('NUMERIC(20,0)', sql)
        self.assertIn('TIMESTAMP(6)', sql)
        self.assertIn('CONSTRAINT "uk_pair" UNIQUE ("id","file_id")', sql)
        self.assertIn('CREATE INDEX "idx_created" ON "rel" ("created","active");', sql)
        self.assertNotIn('ENGINE=', sql)

    def test_mysql_insert(self):
        sql, report = convert_text("INSERT INTO `t` (`a`,`b`) VALUES (1,'你好'),(2,'a;b');", 'mysql_to_opengauss')
        self.assertTrue(report.ready)
        self.assertIn("INSERT INTO \"t\"", sql)
        self.assertIn("'a;b'", sql)

    def test_mysql_comments(self):
        src = "CREATE TABLE `t` (`id` INT COMMENT '编号') ENGINE=InnoDB COMMENT='表';"
        sql, report = convert_text(src, 'mysql_to_opengauss')
        self.assertTrue(report.ready)
        self.assertIn('COMMENT ON COLUMN "t"."id" IS \'编号\';', sql)
        self.assertIn('COMMENT ON TABLE "t" IS \'表\';', sql)

    def test_opengauss_create_table_serial(self):
        src = '''CREATE TABLE "t" ("id" BIGSERIAL PRIMARY KEY, "val" NUMERIC(18,4), "d" TIMESTAMP(6));'''
        sql, report = convert_text(src, 'opengauss_to_mysql')
        self.assertTrue(report.ready)
        self.assertIn('BIGINT AUTO_INCREMENT PRIMARY KEY', sql)
        self.assertIn('DECIMAL(18,4)', sql)
        self.assertIn('DATETIME(6)', sql)

    def test_data_type_override(self):
        sql, report = convert_text('CREATE TABLE `t` (`flag` tinyint(1));', 'mysql_to_opengauss', {'TINYINT(1)':'BOOLEAN'})
        self.assertTrue(report.ready)
        self.assertIn('"flag" BOOLEAN', sql)
        self.assertTrue(any(f.code == 'CUSTOM_MAPPING' for f in report.findings))

    def test_invalid_data_type_override_blocked(self):
        sql, report = convert_text('CREATE TABLE `t` (`id` tinyint(1));', 'mysql_to_opengauss', {'TINYINT(1)':'INVALIDTYPE'})
        self.assertFalse(report.ready)
        self.assertIn('_', report.findings[0].code)
        self.assertNotIn('CREATE TABLE "t"', sql)

    def test_unknown_type_is_blocker(self):
        sql, report = convert_text('CREATE TABLE `t` (`a` ENUM(\'a\',\'b\'));', 'mysql_to_opengauss')
        self.assertEqual(report.blocked, 1)
        self.assertNotIn('CREATE TABLE "t"', sql)

    def test_unsupported_statement_is_not_executable(self):
        sql, report = convert_text('CREATE PROCEDURE p() SELECT 1;', 'mysql_to_opengauss')
        self.assertEqual(report.blocked, 1)
        self.assertIn('DO NOT execute', sql)
        self.assertNotIn('CREATE PROCEDURE p()', sql)

    def test_insert_ignore_blocked(self):
        sql, report = convert_text('INSERT IGNORE INTO `t` VALUES (1);', 'mysql_to_opengauss')
        self.assertEqual(report.blocked, 1)

    def test_hex_literal_blocked(self):
        sql, report = convert_text('INSERT INTO t VALUES (0xAA);', 'mysql_to_opengauss')
        self.assertFalse(report.ready)

    def test_backslash_string_rewritten_safely(self):
        sql, report = convert_text(r"INSERT INTO t VALUES ('a\nb');", 'mysql_to_opengauss')
        self.assertTrue(report.ready)
        self.assertIn(r"E'a\nb'", sql)

    def test_prefix_index_blocked(self):
        src = 'CREATE TABLE `t` (`v` VARCHAR(255), KEY `idx` (`v`(10))) ENGINE=InnoDB;'
        sql, report = convert_text(src, 'mysql_to_opengauss')
        self.assertFalse(report.ready)

    def test_mysql_dump_session_statements(self):
        src = '/*!40101 SET @OLD_CHARACTER_SET_CLIENT=@@CHARACTER_SET_CLIENT */;\nCREATE TABLE `t` (`v` LONGTEXT);'
        sql, report = convert_text(src, 'mysql_to_opengauss')
        self.assertTrue(report.ready)
        self.assertEqual(report.skipped, 1)
        self.assertIn('"v" TEXT', sql)

    def test_unknown_set_is_blocker(self):
        sql, report = convert_text('SET sensitive_business_config=0;', 'mysql_to_opengauss')
        self.assertFalse(report.ready)

    def test_delimiter_aborts_whole_file(self):
        src = 'CREATE TABLE `ok` (`id` INT);\nDELIMITER $$\nCREATE PROCEDURE x() SELECT 1;\nDELIMITER ;'
        sql, report = convert_text(src, 'mysql_to_opengauss')
        self.assertEqual(report.blocked, 1)
        self.assertNotIn('CREATE TABLE', sql)

    def test_copy_stdin_aborts_whole_file(self):
        src = 'CREATE TABLE "ok" (id int);\nCOPY ok FROM stdin;\n1\n\\.\n'
        sql, report = convert_text(src, 'opengauss_to_mysql')
        self.assertEqual(report.blocked, 1)
        self.assertNotIn('CREATE TABLE', sql)

    def test_file_encoding_and_output(self):
        with tempfile.TemporaryDirectory() as directory:
            d = Path(directory)
            source = d / 'demo.sql'
            source.write_bytes('CREATE TABLE `a` (`name` VARCHAR(80));'.encode('gb18030'))
            sql_path, report_path, report = convert_file(source, d, 'mysql_to_opengauss')
            self.assertTrue(report.ready)
            self.assertEqual(sql_path.name, 'demo_opengauss.sql')
            self.assertTrue(report_path.exists())
            self.assertEqual(read_sql(sql_path).splitlines()[0], '-- SQLConverter: mysql -> opengauss')

    def test_config_roundtrip(self):
        with tempfile.TemporaryDirectory() as directory:
            file = Path(directory) / 'conf.json'
            values = {'mysql_to_opengauss': {'TINYINT(1)':'BOOLEAN'}}
            save_overrides(file, values)
            self.assertEqual(load_overrides(file), values)

    def test_custom_mapping_params(self):
        converted, rule = replace_type('DECIMAL(16,3) NOT NULL', 'mysql_to_opengauss', {})
        self.assertEqual(converted, 'NUMERIC(16,3) NOT NULL')
        self.assertEqual(rule, 'DECIMAL(p,s)')


